#!/usr/bin/env ruby
# frozen_string_literal: true
#
# build_site - regenerate the Ruby embedded in docs/index.html from lib/
#
# The browser build (ruby.wasm) executes a copy of the Eliza library inlined
# in a <script type="text/ruby"> tag. This script splices a fresh copy of
# lib/ (plus the DOCTOR script, wrapped in a heredoc) between the BEGIN/END
# markers in docs/index.html, so lib/ stays the single source of truth.
#
# usage: ruby bin/build_site.rb

ROOT = File.expand_path("..", __dir__)
SITE = File.join(ROOT, "docs", "index.html")

BEGIN_MARK = "# --- BEGIN generated by bin/build_site.rb (edit lib/, not this) ---"
END_MARK   = "# --- END generated by bin/build_site.rb ---"

LIBRARY_SOURCES = %w[
  lib/eliza.rb
  lib/eliza/transformation.rb
  lib/eliza/keyword_rule.rb
  lib/eliza/memory_rule.rb
  lib/eliza/script.rb
  lib/eliza/engine.rb
  lib/eliza/cacm_conversation.rb
].freeze

DOCTOR_SCRIPT_FILE = "lib/eliza/scripts/original-1966-cacm.txt"

# the browser runs one inlined blob: no magic comments, no requires
def inlined(source)
  source.lines.reject { |line| line.match?(/\A(# frozen_string_literal|require )/) }.join.strip
end

def doctor_script_constant
  constant = +"module Eliza\n"
  constant << "  # Anthony Hay's verbatim transcription of the DOCTOR script printed in\n"
  constant << "  # the appendix of Weizenbaum's January 1966 CACM paper.\n"
  constant << "  # https://github.com/anthay/ELIZA (CC0 1.0)\n"
  constant << "  DOCTOR_SCRIPT = <<~'CACM_SCRIPT'\n"
  File.read(File.join(ROOT, DOCTOR_SCRIPT_FILE)).each_line do |line|
    constant << (line.strip.empty? ? "\n" : "    #{line}")
  end
  constant << "  CACM_SCRIPT\nend"
end

sources = LIBRARY_SOURCES.map { |path| inlined(File.read(File.join(ROOT, path))) }
generated = ([BEGIN_MARK] + sources + [doctor_script_constant, END_MARK]).join("\n\n")

html = File.read(SITE)
region = /#{Regexp.escape(BEGIN_MARK)}.*#{Regexp.escape(END_MARK)}/m
abort "error: build markers not found in #{SITE}" unless html.match?(region)

File.write(SITE, html.sub(region) { generated })
puts "docs/index.html: embedded #{generated.lines.count} lines of Ruby from lib/"
